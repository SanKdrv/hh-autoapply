"""Поиск «кодовых слов», которые работодатель просит указать в письме.

Многие вакансии содержат требование вида:
«в сопроводительном письме укажите слово "ёжик"»,
«начните письмо со слова Привет», «кодовое слово: БАРСИК».
Такие письма без ключа часто отсеиваются автоматически.
"""
from __future__ import annotations

import re

from .util import norm

TRIGGER = (
    r"(?:укажите|укажи|напишите|напиши|добавьте|вставьте|упомяните|начните|начни|"
    r"перв(?:ым|ое|ого)\s+словом?|кодовое\s+слово|код-?слово|"
    r"ключевое\s+слово|секретное\s+слово|слово-?пароль)"
)

# Ключ в кавычках — самый надёжный случай.
QUOTED = re.compile(
    TRIGGER + r"[^.\n]{0,90}?[«\"'“”„]([^»\"'“”„\n]{2,40})[»\"'“”„]",
    re.I,
)

# «кодовое слово: X», «ключевое слово — X»
LABELLED = re.compile(
    r"(?:кодовое|ключевое|секретное)\s+слово[^.\n]{0,20}?[:—\-]\s*"
    r"([A-Za-zА-Яа-яЁё0-9_\- ]{2,40})",
    re.I,
)

# «укажите слово X» без кавычек
BARE = re.compile(
    TRIGGER + r"[^.\n]{0,60}?слов[оа][^A-Za-zА-Яа-яЁё]{0,4}"
    r"([A-Za-zА-Яа-яЁё0-9_\-]{2,30})",
    re.I,
)

# «первым словом укажите: X» — слово стоит ПЕРЕД глаголом
FIRST_WORD = re.compile(
    r"перв(?:ым|ое|ого)\s+словом?[^.\n]{0,25}?[:—\-]\s*([A-Za-zА-Яа-яЁё0-9_\-]{2,30})",
    re.I,
)

# «начните письмо со слова X» (X может быть фразой из нескольких слов)
START_WITH = re.compile(
    r"(?:начните|начни|начинайте|в\s+начале)\s+[^.\n]{0,40}?"
    r"(?:со\s+словами?|со\s+словом|словом|словами|с\s+словами|с\s+слова)"
    r"[^.\n]{0,10}?([A-Za-zА-Яа-яЁё0-9_\- ]{2,40})",
    re.I,
)

_STOPWORDS = {
    "слово", "слова", "письмо", "письме", "письма", "вакансия", "вакансии",
    "компания", "компании", "отклик", "отклике", "сопроводительном",
    "фраза", "фразы", "фразу", "текст", "тексте", "себя", "себе", "нём", "нем",
}


def _clean(raw: str) -> str:
    value = raw.strip().strip(".,;:!?»«\"'")
    value = re.sub(r"\s+", " ", value)
    return value


def extract_keyword(text: str) -> str:
    """Возвращает кодовое слово из описания вакансии или пустую строку."""
    if not text:
        return ""

    for pattern in (QUOTED, LABELLED, FIRST_WORD, START_WITH, BARE):
        for match in pattern.finditer(text):
            value = _clean(match.group(1))
            if not (2 <= len(value) <= 40):
                continue
            if norm(value) in _STOPWORDS:
                continue
            # отсекаем «укажите слово в письме» без самого слова
            if norm(value).startswith(("в письме", "в сопроводительном")):
                continue
            return value
    return ""


def has_keyword_requirement(text: str) -> bool:
    return bool(re.search(TRIGGER, text or "", re.I))
